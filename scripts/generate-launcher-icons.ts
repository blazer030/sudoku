import sharp from "sharp";
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { ICON_VARIANTS, roundedIconSvg, roundedSvg, type IconVariant } from "./iconArtwork";
import { LEGACY_LAUNCHER_ALIASES, launcherResourceName, type LauncherIconKey } from "../src/theme/launcherIcon";
import { styleIconBackground, styleIconForeground, styleIconMonochrome } from "../src/theme/styleIcons";
import { STYLE_IDS, type StyleId } from "../src/theme/themeIds";
import { BRAND_ICON_BACKGROUND, BRAND_ICON_RESOURCE, brandIconForeground, brandIconMonochrome, brandIconSvg } from "../src/theme/brandIcon";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

interface DensityDef {
    name: string;
    size: number;
}

// Legacy (API 24-25) icon sizes and the adaptive foreground layer's, per density
const DENSITIES: DensityDef[] = [
    { name: "mdpi",    size: 48 },
    { name: "hdpi",    size: 72 },
    { name: "xhdpi",   size: 96 },
    { name: "xxhdpi",  size: 144 },
    { name: "xxxhdpi", size: 192 },
];
const FOREGROUND_SCALE = 108 / 48;

const RES_ROOT = resolve(__dirname, "../android/app/src/main/res");
const MANIFEST_PATH = resolve(__dirname, "../android/app/src/main/AndroidManifest.xml");
const ALIASES_BEGIN = "<!-- BEGIN launcher aliases: generated by scripts/generate-launcher-icons.ts -->";
const ALIASES_END = "<!-- END launcher aliases -->";

// Minimal's themes share their tile artwork, so one foreground per tile colour serves every theme
// that uses it; tactile and paper draw their whole artwork in the foreground, one per icon
const foregroundName = ({ id, style, palette }: IconVariant): string => style === "minimal"
    ? `ic_launcher_tiles_${palette["on-primary"].slice(1).toLowerCase()}_foreground`
    : `${launcherResourceName(id)}_foreground`;

// The monochrome layer is one colour whatever the theme, so one per style
const monochromeName = (style: StyleId): string => `ic_launcher_${style}_monochrome`;

const adaptiveIconXml = (variant: IconVariant): string => {
    const name = launcherResourceName(variant.id);
    return `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${name}_background"/>
    <foreground android:drawable="@mipmap/${foregroundName(variant)}"/>
    <monochrome android:drawable="@mipmap/${monochromeName(variant.style)}"/>
</adaptive-icon>
`;
};

// The app's own icon, which the main activity shows while no theme alias is on
const brandAdaptiveIconXml = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${BRAND_ICON_RESOURCE}_background"/>
    <foreground android:drawable="@mipmap/${BRAND_ICON_RESOURCE}_foreground"/>
    <monochrome android:drawable="@mipmap/${BRAND_ICON_RESOURCE}_monochrome"/>
</adaptive-icon>
`;

const themeColorsXml = (): string => `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="${BRAND_ICON_RESOURCE}_background">${BRAND_ICON_BACKGROUND}</color>
${ICON_VARIANTS.map(variant => `    <color name="${launcherResourceName(variant.id)}_background">${styleIconBackground(variant.style, variant.palette)}</color>`).join("\n")}
</resources>
`;

// No roundIcon: adaptive icons are masked by the launcher, and the legacy icon is already rounded
const aliasXml = (alias: string, icon: LauncherIconKey): string => `        <activity-alias
            android:name=".${alias}"
            android:enabled="false"
            android:icon="@mipmap/${launcherResourceName(icon)}"
            android:label="@string/title_activity_main"
            android:targetActivity=".MainActivity"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>`;

const writeManifestAliases = () => {
    const manifest = readFileSync(MANIFEST_PATH, "utf8");
    const start = manifest.indexOf(ALIASES_BEGIN);
    const end = manifest.indexOf(ALIASES_END);
    if (start === -1 || end === -1) throw new Error("AndroidManifest.xml lacks the launcher alias markers");
    // Each icon's own alias, then the legacy aliases drawing an icon of another key
    const aliases = [
        ...ICON_VARIANTS.map(variant => aliasXml(variant.id, variant.id)),
        ...LEGACY_LAUNCHER_ALIASES.map(alias => aliasXml(alias.key, alias.icon)),
    ].join("\n\n");
    writeFileSync(MANIFEST_PATH, `${manifest.slice(0, start + ALIASES_BEGIN.length)}\n${aliases}\n        ${manifest.slice(end)}`);
};

// Renders one adaptive layer (108dp) at every density
const writeAdaptiveLayer = async (name: string, svg: string) => {
    for (const density of DENSITIES) {
        const size = Math.round(density.size * FOREGROUND_SCALE);
        const outDir = resolve(RES_ROOT, `mipmap-${density.name}`);
        mkdirSync(outDir, { recursive: true });
        await sharp(Buffer.from(svg)).resize(size, size).png().toFile(resolve(outDir, `${name}.png`));
    }
};

// Renders one legacy (pre-adaptive) icon at every density
const writeLegacyIcon = async (name: string, svg: string) => {
    for (const density of DENSITIES) {
        const outDir = resolve(RES_ROOT, `mipmap-${density.name}`);
        mkdirSync(outDir, { recursive: true });
        await sharp(Buffer.from(svg)).resize(density.size, density.size).png().toFile(resolve(outDir, `${name}.png`));
    }
};

const main = async () => {
    // Minimal's themes that share a tile colour share one foreground
    const foregrounds = ICON_VARIANTS
        .map(variant => ({ name: foregroundName(variant), svg: styleIconForeground(variant.style, variant.palette) }))
        .filter((foreground, index, all) => all.findIndex(other => other.name === foreground.name) === index);
    for (const { name, svg } of foregrounds) {
        await writeAdaptiveLayer(name, svg);
    }
    for (const style of STYLE_IDS) {
        await writeAdaptiveLayer(monochromeName(style), styleIconMonochrome(style));
    }

    const xmlDir = resolve(RES_ROOT, "mipmap-anydpi-v26");
    mkdirSync(xmlDir, { recursive: true });
    for (const variant of ICON_VARIANTS) {
        writeFileSync(resolve(xmlDir, `${launcherResourceName(variant.id)}.xml`), adaptiveIconXml(variant));
    }
    writeFileSync(resolve(RES_ROOT, "values/ic_launcher_theme_colors.xml"), themeColorsXml());

    for (const variant of ICON_VARIANTS) {
        await writeLegacyIcon(launcherResourceName(variant.id), roundedIconSvg(variant));
    }

    await writeAdaptiveLayer(`${BRAND_ICON_RESOURCE}_foreground`, brandIconForeground());
    await writeAdaptiveLayer(`${BRAND_ICON_RESOURCE}_monochrome`, brandIconMonochrome());
    writeFileSync(resolve(xmlDir, `${BRAND_ICON_RESOURCE}.xml`), brandAdaptiveIconXml);
    await writeLegacyIcon(BRAND_ICON_RESOURCE, roundedSvg(brandIconSvg()));

    writeManifestAliases();
    console.log(`Done! ${ICON_VARIANTS.length} launcher icons and ${ICON_VARIANTS.length + LEGACY_LAUNCHER_ALIASES.length} aliases generated.`);
};

main().catch((err: unknown) => {
    console.error(err);
    process.exit(1);
});
