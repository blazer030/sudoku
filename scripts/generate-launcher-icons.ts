import sharp from "sharp";
import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";
import { ICON_VARIANTS, iconSvg, type IconTheme } from "./iconArtwork";
import { launcherResourceName } from "../src/theme/launcherIcon";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

interface DensityDef {
    name: string;
    size: number;
}

// Legacy (API 24-25) icon sizes and the adaptive foreground layer's, per density
const DENSITIES: DensityDef[] = [
    { name: "mdpi",    size: 48 },
    { name: "hdpi",    size: 72 },
    { name: "xhdpi",   size: 96 },
    { name: "xxhdpi",  size: 144 },
    { name: "xxxhdpi", size: 192 },
];
const FOREGROUND_SCALE = 108 / 48;

const RES_ROOT = resolve(__dirname, "../android/app/src/main/res");
const MANIFEST_PATH = resolve(__dirname, "../android/app/src/main/AndroidManifest.xml");
const ALIASES_BEGIN = "<!-- BEGIN launcher aliases: generated by scripts/generate-launcher-icons.ts -->";
const ALIASES_END = "<!-- END launcher aliases -->";

const FOREGROUND_LAYER_DP = 108;
const FOREGROUND_GRID_DP = 43.2;
const SOURCE_GRID_START = 48;
const SOURCE_GRID_SIZE = 144;

// Themes share the tile artwork; one foreground per tile colour serves every theme that uses it
const foregroundName = (onPrimary: string): string => `ic_launcher_tiles_${onPrimary.slice(1).toLowerCase()}_foreground`;

const tilesForegroundSvg = (svgContent: string): string => {
    const tiles = svgContent.match(/<rect x="\d+" y="\d+"[^>]*\/>/g) ?? [];
    const scale = FOREGROUND_GRID_DP / SOURCE_GRID_SIZE;
    const offset = (FOREGROUND_LAYER_DP - FOREGROUND_GRID_DP) / 2;
    return [
        `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${FOREGROUND_LAYER_DP} ${FOREGROUND_LAYER_DP}">`,
        `<g transform="translate(${offset} ${offset}) scale(${scale}) translate(-${SOURCE_GRID_START} -${SOURCE_GRID_START})">`,
        ...tiles,
        "</g>",
        "</svg>",
    ].join("\n");
};

const adaptiveIconXml = (variant: IconTheme): string => {
    const name = launcherResourceName(variant.id);
    const foreground = foregroundName(variant.onPrimary);
    return `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${name}_background"/>
    <foreground android:drawable="@mipmap/${foreground}"/>
    <monochrome android:drawable="@mipmap/${foreground}"/>
</adaptive-icon>
`;
};

const themeColorsXml = (): string => `<?xml version="1.0" encoding="utf-8"?>
<resources>
${ICON_VARIANTS.map(variant => `    <color name="${launcherResourceName(variant.id)}_background">${variant.primary}</color>`).join("\n")}
</resources>
`;

// No roundIcon: adaptive icons are masked by the launcher, and the legacy icon is already rounded
const aliasXml = (variant: IconTheme): string => `        <activity-alias
            android:name=".${variant.id}"
            android:enabled="false"
            android:icon="@mipmap/${launcherResourceName(variant.id)}"
            android:label="@string/title_activity_main"
            android:targetActivity=".MainActivity"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>`;

const writeManifestAliases = () => {
    const manifest = readFileSync(MANIFEST_PATH, "utf8");
    const start = manifest.indexOf(ALIASES_BEGIN);
    const end = manifest.indexOf(ALIASES_END);
    if (start === -1 || end === -1) throw new Error("AndroidManifest.xml lacks the launcher alias markers");
    const aliases = ICON_VARIANTS.map(aliasXml).join("\n\n");
    writeFileSync(MANIFEST_PATH, `${manifest.slice(0, start + ALIASES_BEGIN.length)}\n${aliases}\n        ${manifest.slice(end)}`);
};

const main = async () => {
    const tileColors = ICON_VARIANTS.map(variant => variant.onPrimary).filter((color, index, all) => all.indexOf(color) === index);
    for (const onPrimary of tileColors) {
        // The foreground keeps only the tiles, so the primary passed here does not show
        const foregroundSvg = Buffer.from(tilesForegroundSvg(iconSvg({ primary: onPrimary, onPrimary })));
        for (const density of DENSITIES) {
            const size = Math.round(density.size * FOREGROUND_SCALE);
            const outDir = resolve(RES_ROOT, `mipmap-${density.name}`);
            mkdirSync(outDir, { recursive: true });
            await sharp(foregroundSvg).resize(size, size).png().toFile(resolve(outDir, `${foregroundName(onPrimary)}.png`));
        }
    }

    const xmlDir = resolve(RES_ROOT, "mipmap-anydpi-v26");
    mkdirSync(xmlDir, { recursive: true });
    for (const variant of ICON_VARIANTS) {
        writeFileSync(resolve(xmlDir, `${launcherResourceName(variant.id)}.xml`), adaptiveIconXml(variant));
    }
    writeFileSync(resolve(RES_ROOT, "values/ic_launcher_theme_colors.xml"), themeColorsXml());

    for (const variant of ICON_VARIANTS) {
        const svgBuffer = Buffer.from(iconSvg(variant));
        for (const density of DENSITIES) {
            const outDir = resolve(RES_ROOT, `mipmap-${density.name}`);
            mkdirSync(outDir, { recursive: true });
            await sharp(svgBuffer)
                .resize(density.size, density.size)
                .png()
                .toFile(resolve(outDir, `${launcherResourceName(variant.id)}.png`));
        }
    }

    writeManifestAliases();
    console.log(`Done! ${ICON_VARIANTS.length} launcher icons and aliases generated.`);
};

main().catch((err: unknown) => {
    console.error(err);
    process.exit(1);
});
